"""Reproducible experiment matrix for Module 3 validation."""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np

from module3.comparison import compare_spatial_fourier
from module3.io_utils import bgr_to_gray_float64, load_image_bgr
from module3.kernels import KernelSpec, make_kernel


@dataclass(frozen=True)
class ExperimentSpec:
    """One blur experiment from the required validation matrix."""

    experiment: int
    filter_key: str
    kernel_size: int
    observation: str


@dataclass(frozen=True)
class ExperimentRow:
    """One measured experiment result row."""

    experiment: int
    filter_name: str
    kernel_size: int
    mae: float
    mse: float
    rmse: float
    max_abs_error: float
    psnr_db: float
    max_imaginary_abs: float
    observation: str


EXPERIMENT_MATRIX: tuple[ExperimentSpec, ...] = (
    ExperimentSpec(1, "average", 3, "Required average blur baseline."),
    ExperimentSpec(2, "average", 5, "Required larger average blur."),
    ExperimentSpec(3, "gaussian", 5, "Required Gaussian blur row."),
    ExperimentSpec(4, "average", 9, "Larger average kernel tests size trend."),
    ExperimentSpec(5, "gaussian", 3, "Small Gaussian kernel tests size trend."),
    ExperimentSpec(6, "gaussian", 9, "Larger Gaussian kernel tests size trend."),
)


def kernel_for_spec(spec: ExperimentSpec) -> KernelSpec:
    """Create the kernel configured by an experiment specification."""
    return make_kernel(spec.filter_key, spec.kernel_size)


def run_experiment_matrix(image_gray: np.ndarray) -> list[ExperimentRow]:
    """Run every configured experiment on a grayscale image.

    Args:
        image_gray: Single-channel input image.

    Returns:
        One row per configured experiment, with real computed metrics.
    """
    rows: list[ExperimentRow] = []
    for spec in EXPERIMENT_MATRIX:
        kernel_spec = kernel_for_spec(spec)
        result = compare_spatial_fourier(image_gray, kernel_spec.kernel)
        rows.append(
            ExperimentRow(
                experiment=spec.experiment,
                filter_name=kernel_spec.filter_name,
                kernel_size=kernel_spec.size,
                mae=result.metrics.mae,
                mse=result.metrics.mse,
                rmse=result.metrics.rmse,
                max_abs_error=result.metrics.max_abs_error,
                psnr_db=result.metrics.psnr_db,
                max_imaginary_abs=result.max_imaginary_abs,
                observation=spec.observation,
            )
        )
    return rows


def run_experiments_for_image_path(image_path: str | Path) -> list[ExperimentRow]:
    """Load an image and run the full validation matrix."""
    bgr = load_image_bgr(image_path)
    gray = bgr_to_gray_float64(bgr)
    return run_experiment_matrix(gray)


def rows_to_csv(rows: list[ExperimentRow]) -> str:
    """Serialize experiment rows to CSV text."""
    header = (
        "experiment,filter,kernel_size,mae,mse,rmse,max_abs_error,"
        "psnr_db,max_imaginary_abs,observation"
    )
    lines = [header]
    for row in rows:
        psnr = "inf" if np.isinf(row.psnr_db) else f"{row.psnr_db:.12g}"
        lines.append(
            ",".join(
                [
                    str(row.experiment),
                    row.filter_name,
                    str(row.kernel_size),
                    f"{row.mae:.12g}",
                    f"{row.mse:.12g}",
                    f"{row.rmse:.12g}",
                    f"{row.max_abs_error:.12g}",
                    psnr,
                    f"{row.max_imaginary_abs:.12g}",
                    row.observation,
                ]
            )
        )
    return "\n".join(lines) + "\n"


def rows_to_markdown(rows: list[ExperimentRow], *, image_name: str) -> str:
    """Serialize experiment rows to a Markdown table for docs and the web app."""
    lines = [
        "# Experimental Results",
        "",
        f"Input image: `{image_name}`.",
        "",
        "These numbers are generated by `scripts/run_experiments.py` using matched zero "
        "boundary conditions and float64 arithmetic.",
        "",
        "| Experiment | Filter | Kernel Size | Spatial vs. Fourier MAE | MSE | RMSE | Max Abs Error | PSNR (dB) | Observation |",
        "|---:|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        psnr = "inf" if np.isinf(row.psnr_db) else f"{row.psnr_db:.2f}"
        lines.append(
            "| "
            f"{row.experiment} | {row.filter_name} | {row.kernel_size}x{row.kernel_size} | "
            f"{row.mae:.6e} | {row.mse:.6e} | {row.rmse:.6e} | "
            f"{row.max_abs_error:.6e} | {psnr} | {row.observation} |"
        )
    return "\n".join(lines) + "\n"
